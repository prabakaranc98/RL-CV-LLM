"""Writes tikz/memory-bill.tex: memory for the models each method keeps, at 7B and at Qwen3-0.6B.

Bytes per parameter (ZeRO, Rajbhandari et al., arXiv:1910.02054): a model trained with mixed-precision Adam
holds 2 (half-precision weights) + 2 (gradients) + 12 (fp32 weights, momentum, variance) = 16 bytes;
a frozen model in bf16 holds 2 bytes. Activations, the KV cache and buffers are not included.
Every number in the figure is computed here; code/check_numbers.py checks the same values.
"""
import pathlib
T = pathlib.Path(__file__).parent
TRAINED, FROZEN = 16, 2                                  # bytes per parameter
QWEN = 0.596e9                                           # Qwen3-0.6B, from config.json (see check_numbers.py)
SIZES = [("a 7B model", 7e9), ("Qwen3-0.6B", QWEN)]
# (method, [(part, trained?)]) -- the critic is a transformer of the policy's size with a scalar head
METHODS = [("PPO (RLHF)", [("policy", True), ("critic", True), ("RM", False), ("ref", False)]),
           ("GRPO, checker reward", [("policy", True), ("ref", False)]),
           ("DPO", [("policy", True), ("ref", False)])]
STYLE = {"policy": "draw=fern, line width=1pt, fill=ferntint", "critic": "draw=grey700, line width=0.8pt, fill=white",
         "RM": "draw=grey500, line width=0.8pt, fill=grey100", "ref": "draw=grey500, line width=0.8pt, fill=grey300"}
GB = lambda n_params, trained: n_params * (TRAINED if trained else FROZEN) / 1e9

def bill(n):
    return {m: [(p, GB(n, t)) for p, t in parts] for m, parts in METHODS}

if __name__ == "__main__":
    s = 0.062   # cm per GB
    out = ["% generated by gen_memory.py -- do not edit by hand\n\\documentclass[border=8pt]{standalone}\n\\input{pt-style}\n\\begin{document}\n",
           "\\begin{tikzpicture}[font=\\small]\n"]
    y = 0.0; rows = []
    for gname, n in SIZES:
        out.append(f"\\node[font=\\small\\bfseries, anchor=west] at (-4.6,{y + 0.15:.2f}) {{{gname}}};\n")
        y -= 0.75
        for m, parts in bill(n).items():
            x = 0.0
            for p, gb in parts:
                w = gb * s
                out.append(f"\\draw[{STYLE[p]}] ({x:.3f},{y - 0.28:.2f}) rectangle ({x + w:.3f},{y + 0.28:.2f});\n")
                if w > 0.75:
                    lab = f"{p} {gb:.0f} GB" if w > 2.5 else p
                    out.append(f"\\node[font=\\footnotesize, text=ink] at ({x + w / 2:.3f},{y:.2f}) {{{lab}}};\n")
                x += w
            total = sum(gb for _, gb in parts)
            out.append(f"\\node[font=\\small, anchor=east, text=grey700] at (-0.15,{y:.2f}) {{{m}}};\n")
            out.append(f"\\node[font=\\small\\bfseries, anchor=west] at ({x + 0.12:.3f},{y:.2f}) {{{total:.0f} GB}};\n" if total >= 10 else
                       f"\\node[font=\\small\\bfseries, anchor=west] at ({x + 0.12:.3f},{y:.2f}) {{{total:.1f} GB}};\n")
            rows.append((gname, m, total)); y -= 0.8
        y -= 0.35
    top, bot = 0.55, y + 0.6
    out.append(f"\\draw[grey500, dashed, line width=0.8pt] ({80 * s:.3f},{top}) -- ({80 * s:.3f},{bot:.2f});\n")
    out.append(f"\\node[font=\\footnotesize, text=grey700, anchor=south] at ({80 * s:.3f},{top}) {{one 80 GB GPU}};\n")
    # legend: one swatch per part, grouped by what is stored
    ly = bot - 0.55
    def sw(x, y, part): return f"\\draw[{STYLE[part]}] ({x:.2f},{y:.2f}) rectangle ({x + 0.5:.2f},{y - 0.32:.2f});\n"
    out.append(sw(0, ly, "policy") + sw(0.6, ly, "critic"))
    out.append(f"\\node[font=\\footnotesize, anchor=west] at (1.2,{ly - 0.16:.2f}) "
               f"{{trained (policy, critic): weights, gradients and Adam states, {TRAINED} bytes per parameter}};\n")
    out.append(sw(0, ly - 0.55, "RM") + sw(0.6, ly - 0.55, "ref"))
    out.append(f"\\node[font=\\footnotesize, anchor=west] at (1.2,{ly - 0.71:.2f}) "
               f"{{frozen (RM: reward model; ref: reference): bf16 weights only, {FROZEN} bytes per parameter}};\n")
    out.append(f"\\node[font=\\footnotesize, text=grey500, anchor=west] at (0,{ly - 1.25:.2f}) "
               f"{{not included: activations, the KV cache for generation, and framework buffers}};\n")
    out.append("\\end{tikzpicture}\n\\end{document}\n")
    (T / "memory-bill.tex").write_text("".join(out))
    for r in rows: print(f"{r[0]:12s} {r[1]:22s} {r[2]:7.1f} GB")
